#!/usr/bin/env python3
"""tools/harden.py: writes the repo-root _headers for thelatinmass.org (23 Oct 2026, host move to Cloudflare Pages).

Usage (from anywhere):  python tools/harden.py
Run it after ANY edit to an HTML file, then commit the regenerated _headers with the edit.
The Cloudflare Pages project deploys the repo as-is (no build command), so the committed _headers IS what ships.

What it does:
1. Removes any <meta http-equiv="Content-Security-Policy"> from every HTML file. The header below replaces it:
   a meta CSP cannot carry frame-ancestors, and the old one allowed 'unsafe-inline' scripts.
2. Hashes every inline script that runs (no src, not JSON-LD or another data type) in every HTML file
   (sha256 of the exact bytes between the tags) into script-src, so script-src needs no 'unsafe-inline'.
   A changed inline script with a stale _headers would be blocked silently: always rerun this.
   Line endings: git stores these files with LF (core.autocrlf=true on this PC gives a CRLF working copy for
   some files), and Cloudflare serves the LF blob, so CRLF is folded to LF before hashing.
3. Writes _headers: the CSP plus HSTS, nosniff, X-Frame-Options, Referrer-Policy, Permissions-Policy, COOP,
   the media and version.json cache rules, and X-Robots-Tag: noindex ONLY on the pages.dev hosts (host-scoped
   rules), so the real domain thelatinmass.org is never noindexed.
It refuses: inline event handlers (onclick= and the like), javascript: in href or src, and no inline scripts found.
(form action="javascript:void(0)" is allowed: every such form has a submit listener that prevents the submission.)
"""
import base64, hashlib, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIP_DIRS = {".git", ".github", "_audit", "node_modules", "tools"}
SUPABASE = "https://kugcbqfqataxbyjtaume.supabase.co"

def fail(msg):
    print("FAIL: " + msg)
    sys.exit(1)

def read(p):
    with open(p, "r", encoding="utf-8", newline="") as f:
        return f.read()

def write(p, s):
    with open(p, "w", encoding="utf-8", newline="") as f:
        f.write(s)

META_CSP = re.compile(r'[ \t]*<meta\s+http-equiv="Content-Security-Policy"[^>]*>\r?\n?', re.I)
SCRIPT = re.compile(r"<script(\s[^>]*)?>(.*?)</script>", re.S | re.I)
DATA_TYPE = re.compile(r'\btype\s*=\s*"(?!(?:text/javascript|module)")[^"]*"', re.I)
HANDLER = re.compile(r"<[a-zA-Z][^>]*\son[a-z]+\s*=", re.S)
JS_URL = re.compile(r"""(?:href|src)\s*=\s*["']\s*javascript:""", re.I)

html_files = []
for root, dirs, files in os.walk(ROOT):
    dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS)
    html_files += [os.path.join(root, n) for n in sorted(files) if n.endswith(".html")]

hashes, stripped = [], []
for p in html_files:
    t = read(p)
    t2, n = META_CSP.subn("", t)
    if n:
        write(p, t2)
        stripped.append(os.path.relpath(p, ROOT))
        t = t2
    if HANDLER.search(t):
        fail(f"{p} carries an inline event handler (on...=); move it into a script")
    if JS_URL.search(t):
        fail(f"{p} carries a javascript: URL in href or src")
    for m in SCRIPT.finditer(t):
        attrs = m.group(1) or ""
        if re.search(r"\bsrc\s*=", attrs, re.I) or DATA_TYPE.search(attrs):
            continue
        body = m.group(2).replace("\r\n", "\n")
        h = "'sha256-" + base64.b64encode(hashlib.sha256(body.encode("utf-8")).digest()).decode() + "'"
        if h not in hashes:
            hashes.append(h)
if not hashes:
    fail("no inline scripts found: wrong folder?")

csp = "; ".join([
    "default-src 'self'",
    "script-src 'self' " + " ".join(sorted(hashes)) + " https://plausible.io https://static.cloudflareinsights.com",
    "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",   # style="" attributes and <style> blocks
    "font-src 'self' https://fonts.gstatic.com",
    "img-src 'self' data: https:",
    "media-src 'self'",                                                  # /media/audio/*.mp3
    "connect-src 'self' " + SUPABASE + " https://plausible.io https://cloudflareinsights.com",
    "worker-src 'self'",
    "manifest-src 'self'",
    "form-action 'self' " + SUPABASE,
    "frame-ancestors 'none'",
    "base-uri 'self'",
    "object-src 'none'",
    "upgrade-insecure-requests",
])
if "'unsafe-inline'" in re.search(r"script-src([^;]*)", csp).group(1):
    fail("script-src must not carry 'unsafe-inline'")

headers = f"""# GENERATED by tools/harden.py: do not edit by hand, rerun the script after any HTML change.
/*
  Content-Security-Policy: {csp}
  Strict-Transport-Security: max-age=31536000; includeSubDomains
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), magnetometer=(), gyroscope=(), accelerometer=()
  Cross-Origin-Opener-Policy: same-origin

/media/*
  Cache-Control: public, max-age=31536000, immutable

/app/version.json
  Cache-Control: no-store

# The pages.dev copies (production mirror and branch previews) must not compete with thelatinmass.org.
# Host-scoped, so it can never noindex the real domain.
https://thelatinmass-org-site.pages.dev/*
  X-Robots-Tag: noindex
https://:branch.thelatinmass-org-site.pages.dev/*
  X-Robots-Tag: noindex
"""
write(os.path.join(ROOT, "_headers"), headers.replace("\r\n", "\n"))
print(f"harden: {len(html_files)} HTML files, {len(hashes)} inline script hash(es); meta CSP removed from: {', '.join(stripped) or 'none'}")
